inline uint8_t CodepointToByte(uint32_t cp) {
    if (cp < 0x80) return static_cast<uint8_t>(cp);
    const auto& table = NonAsciiTable();
    auto it = std::lower_bound(table.begin(), table.end(), cp,
        [](const CpPair& p, uint32_t v) { return p.codepoint < v; });
    if (it != table.end() && it->codepoint == cp) return it->byte;
    return '?'; // unmappable codepoint: substitute (matches typical lossy codepage transcoding)
}

// Decodes one UTF-8 codepoint starting at s[i]; advances i past it. Malformed sequences are
// treated as a single Latin-1 byte (defensive; XLSX text is always valid UTF-8 in practice).
inline uint32_t DecodeUtf8(const std::string& s, size_t& i) {
    unsigned char c0 = static_cast<unsigned char>(s[i]);
    if (c0 < 0x80) { ++i; return c0; }
    if ((c0 & 0xE0) == 0xC0 && i + 1 < s.size()) {
        uint32_t cp = ((c0 & 0x1Fu) << 6) | (static_cast<unsigned char>(s[i + 1]) & 0x3Fu);
        i += 2; return cp;
    }
    if ((c0 & 0xF0) == 0xE0 && i + 2 < s.size()) {
        uint32_t cp = ((c0 & 0x0Fu) << 12) | ((static_cast<unsigned char>(s[i + 1]) & 0x3Fu) << 6) |
                      (static_cast<unsigned char>(s[i + 2]) & 0x3Fu);
        i += 3; return cp;
    }
    if ((c0 & 0xF8) == 0xF0 && i + 3 < s.size()) {
        uint32_t cp = ((c0 & 0x07u) << 18) | ((static_cast<unsigned char>(s[i + 1]) & 0x3Fu) << 12) |
                      ((static_cast<unsigned char>(s[i + 2]) & 0x3Fu) << 6) | (static_cast<unsigned char>(s[i + 3]) & 0x3Fu);
        i += 4; return cp;
    }
    ++i;
    return c0;
}

inline std::vector<uint8_t> EncodeCp1251(const std::string& utf8) {
    std::vector<uint8_t> out;
    out.reserve(utf8.size());
    size_t i = 0;
    while (i < utf8.size()) {
        uint32_t cp = DecodeUtf8(utf8, i);
        out.push_back(CodepointToByte(cp));
    }
    return out;
}

