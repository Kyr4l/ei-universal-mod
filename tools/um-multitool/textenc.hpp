inline void AppendUtf8(std::string& o, uint32_t cp) {
    if (cp < 0x80) o += static_cast<char>(cp);
    else if (cp < 0x800) { o += static_cast<char>(0xC0 | (cp >> 6)); o += static_cast<char>(0x80 | (cp & 0x3F)); }
    else { o += static_cast<char>(0xE0 | (cp >> 12)); o += static_cast<char>(0x80 | ((cp >> 6) & 0x3F)); o += static_cast<char>(0x80 | (cp & 0x3F)); }
}

inline std::string Decode(Enc e, const std::vector<uint8_t>& b) {
    if (e == Enc::Utf8) return std::string(b.begin(), b.end());
    if (e == Enc::Cp1251) return cp1251::DecodeCp1251(b.data(), b.size());
    if (e == Enc::Cp1250) return cp1250::ToUtf8(b);
    const uint16_t* high = e == Enc::Cp866 ? Cp866High() : Koi8rHigh();
    std::string o;
    o.reserve(b.size());
    for (uint8_t c : b) AppendUtf8(o, c < 0x80 ? c : high[c - 0x80]);
    return o;
}

inline std::vector<uint8_t> Encode(Enc e, const std::string& utf8) {
    if (e == Enc::Utf8) return std::vector<uint8_t>(utf8.begin(), utf8.end());
    if (e == Enc::Cp1251) return cp1251::EncodeCp1251(utf8);
    std::vector<uint8_t> o;
    o.reserve(utf8.size());
    size_t i = 0;
    while (i < utf8.size()) {
        const uint32_t cp = cp1251::DecodeUtf8(utf8, i);
        if (e == Enc::Cp1250) { o.push_back(cp1250::FromCodepoint(cp)); continue; }
        if (cp < 0x80) { o.push_back(static_cast<uint8_t>(cp)); continue; }
        const uint16_t* high = e == Enc::Cp866 ? Cp866High() : Koi8rHigh();
        uint8_t out = '?';
        for (int k = 0; k < 128; ++k) if (high[k] == cp) { out = static_cast<uint8_t>(0x80 + k); break; }
        o.push_back(out);
    }
    return o;
}

