enum class Enc { Utf8, Cp1251, Cp866, Cp1250, Koi8r };
constexpr int kCount = 5;
inline const char* Name(Enc e) {
    static const char* const n[kCount] = {"UTF-8", "CP1251", "CP866", "CP1250", "KOI8-R"};
    return n[static_cast<int>(e)];
}

