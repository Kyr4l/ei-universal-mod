# Makes quest_skeleton.hpp from the mod's z10q1.mob (a quest map with one unit): python3 gen_quest_skeleton.py  (run in this folder)
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', '..', 'resources', 'universal-mod', 'mob', 'z10q1.mob')
b = open(src, 'rb').read()
out = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Copyright (C) 2026 Kyr4l',
       '// A quest map with one unit (z10q1.mob of the mod, %d bytes): the frame the Quest Builder fills. Its unit is the one every new unit is a copy of.' % len(b),
       '// Generated by tools/um-multitool/mapedit/gen_quest_skeleton.py; do not edit.', '#pragma once', '', '#include <cstdint>', '', 'namespace qdraft {', '',
       'inline const uint8_t kSkeletonMob[] = {']
for i in range(0, len(b), 24):
    out.append('    ' + ', '.join('0x%02x' % x for x in b[i:i + 24]) + ',')
out += ['};', 'inline constexpr unsigned kSkeletonMobSize = %d;' % len(b), '', '} // namespace qdraft', '']
open(os.path.join(here, 'quest_skeleton.hpp'), 'w').write('\n'.join(out))
